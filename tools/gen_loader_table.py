#!/usr/bin/env python3
"""Generate AICLoaderSeq.h (firmware upload for the a69c:8d80 ROM bootloader) from a usbmon capture.

Input: tshark fields of the bootloader device's bulk transfers, one per line:
    frame.number <TAB> usb.endpoint_address <TAB> usb.capdata
  tshark -r bringup.pcapng -Y 'usb.device_address==<boot dev> && usb.transfer_type==3 && usb.capdata' \
         -T fields -e frame.number -e usb.endpoint_address -e usb.capdata > bootloader_bulk.tsv
Every OUT frame (EP 0x01) is replayed verbatim. For DBG_MEM_READ the captured reply (addr, value) is stored so
the kext can refuse a chip whose reads differ (other revision / firmware layout).
shortcut: verbatim replay of Linux aic_load_fw for one chip (D80 U02); port aicfw_download_fw_8800d80 for others.
"""
import struct
import sys

DBG_MEM_READ, DBG_START_APP = 0x0400, 0x040D


def main(tsv, out):
    rows = []
    for line in open(tsv):
        _fr, ep, hx = line.rstrip("\n").split("\t")
        rows.append((ep, bytes.fromhex(hx.replace(":", ""))))
    frames, expect = [], []
    for i, (ep, b) in enumerate(rows):
        if ep != "0x01":
            continue
        mid = struct.unpack_from("<H", b, 8)[0]
        exp = b""
        if mid == DBG_MEM_READ:
            reply = next(r for e, r in rows[i + 1:] if e == "0x82")
            assert struct.unpack_from("<H", reply, 4)[0] == mid + 1
            exp = reply[16:24]                     # dbg_mem_read_cfm: memaddr, memdata
        frames.append(b)
        expect.append(exp)
    ids = [struct.unpack_from("<H", f, 8)[0] for f in frames]
    assert ids[-1] == DBG_START_APP and ids.count(DBG_START_APP) == 1

    blob = b"".join(frames)
    with open(out, "w") as fh:
        fh.write("// Generated by tools/gen_loader_table.py from captures/bootloader_bulk.tsv. Do not edit.\n")
        fh.write("// Contains AICSemi firmware (from the Linux aic8800 package); for personal use, do not redistribute.\n")
        fh.write("#pragma once\n#include <stdint.h>\n\n")
        fh.write("static const uint8_t kAICLoaderBlob[] = {\n")
        for i in range(0, len(blob), 32):
            fh.write("    " + ",".join(f"0x{x:02x}" for x in blob[i:i + 32]) + ",\n")
        fh.write("};\n\nstruct AICLoaderFrame { uint32_t off; uint16_t len; uint16_t id; uint8_t expect[8]; uint8_t hasExpect; };\n")
        fh.write("static const AICLoaderFrame kAICLoaderSeq[] = {\n")
        off = 0
        for f, mid, exp in zip(frames, ids, expect):
            e = ",".join(f"0x{x:02x}" for x in (exp or bytes(8)))
            fh.write(f"    {{{off}, {len(f)}, 0x{mid:04x}, {{{e}}}, {1 if exp else 0}}},\n")
            off += len(f)
        fh.write("};\nstatic const uint32_t kAICLoaderSeqCount = sizeof(kAICLoaderSeq) / sizeof(kAICLoaderSeq[0]);\n")
    print(f"{len(frames)} frames, {len(blob)} bytes -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
