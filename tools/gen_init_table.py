#!/usr/bin/env python3
"""Generate kext/AICInitSeq.h from a tshark bulk.tsv capture.

Takes the first init pass (up to and including MM_ADD_IF_REQ) plus SCANU_VENDOR_IE_REQ
and SCANU_START_REQ. Frames are replayed verbatim by the kext for now.
shortcut: frames are verbatim from one capture (MAC/channel list baked in); decode params once the kext talks to the chip.
"""
import struct
import sys

MM_ADD_IF_REQ, SCANU_VENDOR_IE_REQ, SCANU_START_REQ = 0x0006, 0x1007, 0x1000


def main(tsv, out):
    tx = []
    for line in open(tsv):
        _fr, ep, _urb, hx = line.rstrip("\n").split("\t")
        if ep == "0x02":
            tx.append(bytes.fromhex(hx.replace(":", "")))
    ids = [struct.unpack_from("<H", f, 8)[0] for f in tx]
    first_add_if = ids.index(MM_ADD_IF_REQ)
    seq = tx[:first_add_if + 1]
    seq.append(tx[ids.index(SCANU_VENDOR_IE_REQ)])
    seq.append(tx[ids.index(SCANU_START_REQ)])
    assert [struct.unpack_from("<H", f, 8)[0] for f in seq][-1] == SCANU_START_REQ

    with open(out, "w") as fh:
        fh.write("// Generated by tools/gen_init_table.py from captures/bulk.tsv. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        for i, f in enumerate(seq):
            fh.write(f"static const uint8_t kAICFrame{i}[] = {{{', '.join(f'0x{b:02x}' for b in f)}}};\n")
        fh.write("\nstruct AICInitFrame { const uint8_t *data; uint32_t len; uint16_t id; };\n")
        fh.write("static const AICInitFrame kAICInitSeq[] = {\n")
        for i, f in enumerate(seq):
            fh.write(f"    {{kAICFrame{i}, {len(f)}, 0x{struct.unpack_from('<H', f, 8)[0]:04x}}},\n")
        fh.write("};\nstatic const uint32_t kAICInitSeqCount = sizeof(kAICInitSeq) / sizeof(kAICInitSeq[0]);\n")
    print(f"{len(seq)} frames -> {out}: " + " ".join(f"0x{struct.unpack_from('<H', f, 8)[0]:04x}" for f in seq))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
